const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  await page.goto('file://' + path.resolve(__dirname, 'index.html'));
  await page.waitForTimeout(1000);
  await page.click('[data-act="howto"]'); await page.waitForTimeout(300);
  await page.click('[data-act="tut-solo"]'); await page.waitForTimeout(800);
  const run = (sec, a) => page.evaluate(([sec, a]) => { const I = (o = {}) => Object.assign({ left: false, right: false, jump: false, stick: false, pull: false, release: false }, o); for (let i = 0; i < sec * 60; i++) { TYA.over[0] = typeof a === 'function' ? I(a(i)) : I(a); TYA.Game.update(1 / 60); } TYA.over[0] = null; const tu = TYA.Game.G.tutorial; return tu ? tu.step + ':' + tu.done.join(',') : 'none'; }, [sec, a]);
  const log = [];
  log.push('move ' + await run(0.7, { right: true }) + ' ' + await run(0.9, { left: true }));
  await page.screenshot({ path: 'shots/tut-1.png' });
  log.push('jump ' + await run(1.6, null) );
  log.push('jump2 ' + await page.evaluate(() => { const I = o => Object.assign({ left: false, right: false, jump: false, stick: false, pull: false, release: false }, o); for (let k = 0; k < 2; k++) { for (let i = 0; i < 6; i++) { TYA.over[0] = I({ jump: true }); TYA.Game.update(1 / 60); } for (let i = 0; i < 70; i++) { TYA.over[0] = I({}); TYA.Game.update(1 / 60); } } return TYA.Game.G.tutorial.step; }));
  log.push('pull ' + await run(2.2, { pull: true }));
  await page.screenshot({ path: 'shots/tut-3.png' });
  log.push('release ' + await run(3.0, { release: true }));
  log.push('ruler ' + await page.evaluate(() => { const G = TYA.Game.G, A = G.players[0]; A.x = 960; A.y = 452 - A.r - 2; A.vx = 0; A.vy = 0; for (let i = 0; i < 90; i++) TYA.Game.update(1 / 60); return G.tutorial.step; }));
  log.push('stick ' + await run(1.6, { stick: true }));
  await page.screenshot({ path: 'shots/tut-6.png' });
  await run(1.0, {});
  log.push('sling ' + await run(1.6, { stick: true, pull: true }) + ' ' + await run(0.6, {}));
  await run(1.0, {});
  log.push('ram ' + await page.evaluate(() => { const G = TYA.Game.G, [A, B] = G.players; B.stuck = false; B.x = 1260; B.y = 640 - B.r; B.stickCd = 0; for (let i = 0; i < 20; i++) TYA.Game.update(1 / 60); A.stuck = false; A.x = 1080; A.y = 640 - A.r; A.vx = 0; A.vy = 0; return G.tutorial.step; }));
  log.push('ram2 ' + await run(1.6, { right: true }));
  await page.screenshot({ path: 'shots/tut-done.png' });
  log.push('end ' + await run(7, {}));
  log.push('ui ' + await page.evaluate(() => TYA.UI.current + ' ' + TYA.Game.G.state));
  console.log(log.join('\n'));
  console.log('ERRORS', errors.join('\n'));
  await browser.close();
})();
